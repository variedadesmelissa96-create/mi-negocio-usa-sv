-- Cada usuario autenticado solo puede ver y modificar sus propios productos.

create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  nombre text not null,
  categoria text not null default 'Otros',
  cantidad integer not null default 1 check (cantidad > 0),
  stock integer not null default 0 check (stock >= 0),
  costo numeric(12,2) not null default 0 check (costo >= 0),
  extra numeric(12,2) not null default 0 check (extra >= 0),
  precio numeric(12,2) not null default 0 check (precio >= 0),
  lote text not null default '',
  vendidas integer not null default 0 check (vendidas >= 0),
  ganancia numeric(12,2) not null default 0,
  created_at timestamptz not null default now()
);

alter table public.productos enable row level security;

drop policy if exists "Cada usuario ve sus productos" on public.productos;
create policy "Cada usuario ve sus productos"
on public.productos for select
to authenticated
using (auth.uid() = user_id);

drop policy if exists "Cada usuario agrega sus productos" on public.productos;
create policy "Cada usuario agrega sus productos"
on public.productos for insert
to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Cada usuario actualiza sus productos" on public.productos;
create policy "Cada usuario actualiza sus productos"
on public.productos for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Cada usuario elimina sus productos" on public.productos;
create policy "Cada usuario elimina sus productos"
on public.productos for delete
to authenticated
using (auth.uid() = user_id);

create index if not exists productos_user_id_idx on public.productos(user_id);
